"""R22 proof that cinematic images are the ORIGINAL owner-provided WebP frames."""
import hashlib
import importlib.util
import json
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("r22_visuals", ROOT / "tools/r22_extract_cinematic_assets.py")
visuals = importlib.util.module_from_spec(spec)
spec.loader.exec_module(visuals)

EXPECTED_SHA = {
 "visual-station.webp": "948eeac979e8af0ae5ada82a6913f7e456e81d0fdaf6a472fab17518d22ef69d",
 "visual-city.webp": "d433b67afc441ed247ef2d344be0412c9367411849cb237e0a9a7abbff27b379",
 "visual-cascade.webp": "96ca90428329065a921aa12ff19d812a2d989abf65d60c73dfbf7afabcc98239",
 "visual-hero.webp": "a5285dd4739a3a0c759a6d39623db03a2e29fbb5f6b1b8085ad11f00ed9af8e7",
 "visual-archive.webp": "006c06050f123e5ddbe917cf26739109f09185dfd3383ecb73d68694efa458b5",
 "visual-control.webp": "b0829a14edd8af1534f03dced934492fe2091a15f833d36721641979c6947d02",
 "visual-operator.webp": "680de6701e5af55ebb475b8ad6780c1d4908fe54c4c5626695dcf98b28bb569a",
 "visual-earthrise.webp": "13bb749d30b99116b9237b8624fd7c965d855078af6833cc7aee73ad5ecc5d0a",
}


class CinematicAssetTests(unittest.TestCase):
    def test_exact_original_owner_assets_have_immutable_sha256(self):
        generated = visuals.extract(ROOT / "site")
        self.assertEqual(set(generated), set(EXPECTED_SHA))
        for name, data in generated.items():
            self.assertEqual(data[:4], b"RIFF", name)
            self.assertEqual(data[8:12], b"WEBP", name)
            self.assertEqual(hashlib.sha256(data).hexdigest(), EXPECTED_SHA[name], name)

    def test_no_outbound_image_fetch_or_unreviewed_source(self):
        data = (ROOT / "tools/r22_extract_cinematic_assets.py").read_text()
        self.assertNotIn("requests.get", data)
        self.assertNotIn("urlopen(", data)
        self.assertNotIn("subprocess", data)
        self.assertEqual(set(visuals.PLAN.values()), set(visuals.PLAN.values()))
        self.assertEqual({x[0] for x in visuals.PLAN.values()},
                         {"film-opspilot.html", "film-intentgraph.html"})

    def test_dist_images_are_present_after_public_build(self):
        dist = ROOT / "dist"
        if not (dist / "build-manifest.json").is_file():
            self.skipTest("dist generated by public builder in integration job")
        manifest = json.loads((dist / "build-manifest.json").read_text())
        for name, digest in EXPECTED_SHA.items():
            self.assertTrue((dist / name).is_file(), name)
            self.assertEqual(manifest["files"].get(name), digest)


if __name__ == "__main__":
    unittest.main()
